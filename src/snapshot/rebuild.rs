pub struct RebuiltGSnapshot {
    pub env: Environment,
    pub key: InvalidationKey,
}

#[derive(Debug)]
pub enum RebuildError {
    BadMagic,
    UnsupportedSchemaVersion(u32),
    CorruptFlat(String),
    BincodeDecode(bincode::Error),
    RegisterFailure(String),
}

impl std::fmt::Display for RebuildError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            RebuildError::BadMagic => write!(f, "bad snapshot magic"),
            RebuildError::UnsupportedSchemaVersion(v) => {
                write!(f, "unsupported schema version {v}")
            }
            RebuildError::CorruptFlat(msg) => write!(f, "corrupt flat payload: {msg}"),
            RebuildError::BincodeDecode(e) => write!(f, "entry decode failed: {e}"),
            RebuildError::RegisterFailure(msg) => write!(f, "register failure: {msg}"),
        }
    }
}

impl std::error::Error for RebuildError {}

pub(crate) fn corrupt(msg: impl Into<String>) -> RebuildError {
    RebuildError::CorruptFlat(msg.into())
}

/// A context of length 1 (just the root) marks a pair that was inserted
/// top-level at draft time; longer contexts are flatten-generated and
/// must not be re-inserted (see module doc).
fn is_top_level(ctx: &[Tn]) -> bool {
    ctx.len() == 1
}

/// Decode a whole G-snapshot file (64-byte header + flat payload) back
/// into a frozen [`Environment`] plus the invalidation key it was written
/// under. The caller compares the key against the current inputs.
pub fn rebuild(bytes: &[u8]) -> Result<RebuiltGSnapshot, RebuildError> {
    if bytes.len() < HEADER_LEN {
        return Err(corrupt(format!(
            "file shorter than header: {} bytes",
            bytes.len()
        )));
    }
    let magic = u64::from_le_bytes(bytes[0..8].try_into().unwrap());
    if magic != G_SNAPSHOT_MAGIC {
        return Err(RebuildError::BadMagic);
    }
    let version = u32::from_le_bytes(bytes[8..12].try_into().unwrap());
    if version != G_SNAPSHOT_SCHEMA_VERSION {
        return Err(RebuildError::UnsupportedSchemaVersion(version));
    }
    let mut key = [0u8; 32];
    key.copy_from_slice(&bytes[16..48]);
    let key = InvalidationKey(key);

    let reader = flat::Reader::try_open(&bytes[HEADER_LEN..]).map_err(corrupt)?;
    let env = rebuild_env(&reader)?;
    Ok(RebuiltGSnapshot { env, key })
}

fn timing_enabled() -> bool {
    std::env::var_os("CREMA_DEBUG_SNAPSHOT_TIMING").is_some_and(|v| v == "1")
}

fn rebuild_env(reader: &flat::Reader<'_>) -> Result<Environment, RebuildError> {
    let timing = timing_enabled();
    let t0 = std::time::Instant::now();

    let mut draft = EnvironmentDraft::new();

    let mut entry_map: FxHashMap<u64, MEntry> = FxHashMap::default();
    for (id, bytes) in reader.iter_entries() {
        let entry: MEntry = bincode::deserialize(bytes).map_err(RebuildError::BincodeDecode)?;
        entry_map.insert(id, entry);
    }
    let t_decode = t0.elapsed();

    let ops = {
        let tables = DecodeTables::intern_from(reader, draft.names())?;
        let mut dec = Decoder::new(&tables);
        dec.collect_ops(&entry_map)?
    };
    let t_tables = t0.elapsed();

    for op in ops {
        op.apply(&mut draft)
            .map_err(RebuildError::RegisterFailure)?;
    }
    let env = match draft.build() {
        Ok(env) => env,
        Err((e, names)) => {
            return Err(RebuildError::RegisterFailure(e.format_with(&names)));
        }
    };
    if timing {
        eprintln!(
            "g-snapshot: rebuild breakdown: entry decode {:.1}ms, tables+ast {:.1}ms, insert+build {:.1}ms",
            t_decode.as_secs_f64() * 1000.0,
            (t_tables - t_decode).as_secs_f64() * 1000.0,
            (t0.elapsed() - t_tables).as_secs_f64() * 1000.0,
        );
    }
    Ok(env)
}

/// Recursively register the flat type-name chain for `id` into `names`'
/// overlay `TypeNameInterner`, verifying the content-addressed recipe
/// reproduces the stored id (the inverse of `convert::Cx::tn`'s drift
/// check).
///
/// `visited` is a memo scoped to one [`DecodeTables::intern_from`] call.
/// Unlike the id-to-`TypeName` lookup table this function's predecessor
/// (ADR-0028 F2) used to build, it only needs to remember "already
/// walked" to skip re-registering a shared prefix, not the resulting
/// `TypeName`: any raw id reconstructs directly via `TypeName::from_hash`
/// (content addressing, ADR-0025).
fn ensure_tn_registered(
    id: u64,
    reader: &flat::Reader<'_>,
    names: &NameTable,
    visited: &mut FxHashSet<u64>,
    depth: usize,
) -> Result<(), RebuildError> {
    if visited.contains(&id) {
        return Ok(());
    }
    if depth > 4096 {
        return Err(corrupt("type-name parent chain too deep (cyclic?)"));
    }
    let (parent, seg, absolute) = reader
        .tn_entry(id)
        .ok_or_else(|| corrupt(format!("missing type-name entry {id:#x}")))?;
    let t = if parent == 0 {
        names.type_name_root(absolute)
    } else {
        ensure_tn_registered(parent, reader, names, visited, depth + 1)?;
        let p = TypeName::from_hash(parent);
        let seg_str = reader
            .sym_str(seg)
            .ok_or_else(|| corrupt(format!("missing segment symbol {seg:#x}")))?;
        let sym = names.intern_symbol(seg_str);
        names.append_type_name(p, sym)
    };
    if t.get() != id {
        return Err(corrupt(format!("type-name recipe drift for {id:#x}")));
    }
    visited.insert(id);
    Ok(())
}

/// Deferred draft insertion — decoding borrows the draft's `NameTable`
/// immutably, so inserts are collected first and applied after that
/// borrow ends.
enum InsertOp {
    Class(DeclOrigin, Context, Arc<cd::ClassDeclaration>),
    Module(DeclOrigin, Context, Arc<cd::ModuleDeclaration>),
    Interface(DeclOrigin, Context, Arc<cd::InterfaceDeclaration>),
    TypeAlias(DeclOrigin, Context, Arc<cd::TypeAliasDeclaration>),
    Constant(DeclOrigin, Context, Arc<cd::ConstantDeclaration>),
    Global(DeclOrigin, Context, Arc<cd::GlobalDeclaration>),
    ClassAlias(DeclOrigin, Context, Arc<cd::ClassAliasDeclaration>),
    ModuleAlias(DeclOrigin, Context, Arc<cd::ModuleAliasDeclaration>),
}

impl InsertOp {
    fn apply(self, draft: &mut EnvironmentDraft) -> Result<(), String> {
        let format = |draft: &EnvironmentDraft, e: crate::environment::draft::BuildError| {
            e.format_with(draft.names())
        };
        match self {
            InsertOp::Class(f, c, d) => draft
                .insert_class_decl(f, c, d)
                .map_err(|e| format(draft, e)),
            InsertOp::Module(f, c, d) => draft
                .insert_module_decl(f, c, d)
                .map_err(|e| format(draft, e)),
            InsertOp::Interface(f, c, d) => draft
                .insert_interface_decl(f, c, d)
                .map_err(|e| format(draft, e)),
            InsertOp::TypeAlias(f, c, d) => draft
                .insert_type_alias(f, c, d)
                .map_err(|e| format(draft, e)),
            InsertOp::Constant(f, c, d) => {
                draft.insert_constant(f, c, d).map_err(|e| format(draft, e))
            }
            InsertOp::Global(f, c, d) => draft.insert_global(f, c, d).map_err(|e| format(draft, e)),
            InsertOp::ClassAlias(f, c, d) => draft
                .insert_class_alias(f, c, d)
                .map_err(|e| format(draft, e)),
            InsertOp::ModuleAlias(f, c, d) => draft
                .insert_module_alias(f, c, d)
                .map_err(|e| format(draft, e)),
        }
    }
}


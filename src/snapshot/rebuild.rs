    pub(crate) fn class_decl(
        &mut self,
        entries: &EntrySource<'_>,
        d: &Arc<MClassDeclaration>,
        own_ctx: &[Tn],
    ) -> Result<cd::ClassDeclaration, RebuildError> {
        let mut child_ctx: Vec<Tn> = own_ctx.to_vec();
        child_ctx.push(d.name);
        Ok(cd::ClassDeclaration {
            name: self.tn(d.name)?,
            type_params: self.type_params(&d.type_params)?,
            super_class: d
                .super_class
                .as_ref()
                .map(|s| self.class_super(s))
                .transpose()?,
            members: d
                .members
                .iter()
                .map(|m| {
                    Ok(match m {
                        MBodyMember::Member(m) => cd::ClassMember::Member(self.member(m)?),
                        MBodyMember::Declaration(r) => {
                            cd::ClassMember::Declaration(self.decl_ref(entries, r, &child_ctx)?)
                        }
                    })
                })
                .collect::<Result<_, RebuildError>>()?,
            annotations: self.annotations(&d.annotations)?,
            location: d.location.as_ref().map(|l| cl::ClassDeclarationLocation {
                range: self.range(&l.range),
                keyword_range: self.range(&l.keyword_range),
                name_range: self.range(&l.name_range),
                end_range: self.range(&l.end_range),
                type_params_range: self.opt_range(&l.type_params_range),
                lt_range: self.opt_range(&l.lt_range),
            }),
            source_file: self.opt_name(d.source_file)?,
            comment: self.comment(&d.comment)?,
        })
    }

    pub(crate) fn module_decl(
        &mut self,
        entries: &EntrySource<'_>,
        d: &Arc<MModuleDeclaration>,
        own_ctx: &[Tn],
    ) -> Result<cd::ModuleDeclaration, RebuildError> {
        let mut child_ctx: Vec<Tn> = own_ctx.to_vec();
        child_ctx.push(d.name);
        Ok(cd::ModuleDeclaration {
            name: self.tn(d.name)?,
            type_params: self.type_params(&d.type_params)?,
            self_types: d
                .self_types
                .iter()
                .map(|s| self.module_self(s))
                .collect::<Result<_, _>>()?,
            members: d
                .members
                .iter()
                .map(|m| {
                    Ok(match m {
                        MBodyMember::Member(m) => cd::ModuleMember::Member(self.member(m)?),
                        MBodyMember::Declaration(r) => {
                            cd::ModuleMember::Declaration(self.decl_ref(entries, r, &child_ctx)?)
                        }
                    })
                })
                .collect::<Result<_, RebuildError>>()?,
            annotations: self.annotations(&d.annotations)?,
            location: d.location.as_ref().map(|l| cl::ModuleDeclarationLocation {
                range: self.range(&l.range),
                keyword_range: self.range(&l.keyword_range),
                name_range: self.range(&l.name_range),
                end_range: self.range(&l.end_range),
                type_params_range: self.opt_range(&l.type_params_range),
                colon_range: self.opt_range(&l.colon_range),
                self_types_range: self.opt_range(&l.self_types_range),
            }),
            source_file: self.opt_name(d.source_file)?,
            comment: self.comment(&d.comment)?,
        })
    }


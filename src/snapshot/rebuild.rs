//! G-snapshot reverse decode — flat bytes → mirror → crema AST → `EnvironmentDraft`
//! → frozen [`Environment`] (ADR-0028 slice 1c).
//!
//! Reconstruction goes through `EnvironmentDraft::insert_*` + `build()`
//! rather than assembling a frozen value directly, so the rebuilt
//! environment passes the same identity validation / flatten / normalize
//! passes a cold build does.
//!
//! Two invariants this module leans on:
//!
//! - Symbol / TypeName ids are content-addressed (ADR-0025), so interning
//!   the snapshot's strings into a fresh `NameTable` reproduces the exact
//!   ids stored in the flat tables. Each re-derivation is verified and a
//!   mismatch surfaces as [`RebuildError::CorruptFlat`].
//! - The draft only ever holds top-level declarations (context length 1);
//!   flatten-generated entries (context length >= 2) are regenerated by
//!   `build()` from the parents' member trees. Re-inserting them here
//!   would double-register every nested declaration.

